    private static void savePDF(String generateFileName, Context context) {

        String targetPDF;

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            //dir = new File(Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOCUMENTS) + "/" + FolderName);

            targetPDF = new File(Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOCUMENTS).toURI()) + "/" + generateFileName + ".pdf";
        } else {
            targetPDF = new File(Environment.getExternalStorageDirectory().toURI()) + "/" + generateFileName + ".pdf";

        }

        PdfDocument document = new PdfDocument();

        File file = new File(targetPDF);
        Log.d("dataxx", "savePDF: " + targetPDF);
        try {
            FileOutputStream fileOutputStream = new FileOutputStream(file);
            document.writeTo(fileOutputStream);
            Toast.makeText(context, "Successfully saved at " + targetPDF, Toast.LENGTH_SHORT).show();
            document.close();
            fileOutputStream.close();
            //openPDF(targetPDF, context);
        } catch (Exception e) {
            e.printStackTrace();
            Log.d("errorxx", e.getMessage());
            Toast.makeText(context, e.getMessage(), Toast.LENGTH_SHORT).show();

            //openPDF(targetPDF, context);
        }
    }

    @SuppressLint("SimpleDateFormat")
    private static String generateFileName(String fileName) {


        return fileName + new SimpleDateFormat("yyMMddHHmmss").format(Calendar.getInstance().getTime());
    }

